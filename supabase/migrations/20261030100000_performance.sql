alter policy profiles_read on public.profiles using (id = (select auth.uid()) or exists (
  select 1 from public.agency_members mine join public.agency_members theirs on theirs.agency_id = mine.agency_id
   where mine.user_id = (select auth.uid()) and theirs.user_id = profiles.id));
alter policy agencies_read on public.agencies using (public.app_is_agency_member(id) or exists (
  select 1 from public.client_portal_users u where u.agency_id = agencies.id and u.user_id = (select auth.uid())));
alter policy client_portal_users_read on public.client_portal_users using (public.app_is_agency_member(agency_id) or user_id = (select auth.uid()));
alter policy notifications_member_read on public.notifications using (public.app_is_agency_member(agency_id) and (user_id is null or user_id = (select auth.uid())));
alter policy team_reads_read on public.team_reads using (user_id = (select auth.uid()));
alter policy push_devices_read on public.push_devices using (user_id = (select auth.uid()));
alter policy push_prefs_read on public.push_prefs using (user_id = (select auth.uid()));

